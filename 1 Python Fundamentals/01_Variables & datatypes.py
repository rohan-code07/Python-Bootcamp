# In Python,Variables are used to store data that can be used and manipulated in a program.A variable is created when you assign a value to it using the = operator.

# Variable Naming Rules:

# Variable names can contain letters, numbers, and underscores.
# Variable names must start with a letter or underscore.
# Variable names are case-sensitive.
# Avoid using Python keywords as variable names (e.g., print, if, else).

# Data Types in Python:

# Integers (int): Whole numbers (e.g., 10, -5).
# Floats (float): Decimal numbers (e.g., 3.14, -0.001).
# Strings (str): Text data enclosed in quotes (e.g., "Hello", 'Python').
# Booleans (bool): Represents True or False.
# Lists: Ordered, mutable collections (e.g., [1, 2, 3]).
# Tuples: Ordered, immutable collections (e.g., (1, 2, 3)).
# Sets: Unordered collections of unique elements (e.g., {1, 2, 3}).
# Dictionaries: Key-value pairs (e.g., {"name": "Alice", "age": 25}).


name = 'Rohan'   # string
print(name)
print(type(name))

age = 18         # integer
print(age)
print(type(age))

percent = 82.2   # float
print(percent)
print(type(percent))

is_completed = True    # Boolean
print(is_completed)
print(type(is_completed))

