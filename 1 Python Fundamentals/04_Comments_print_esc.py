# Comments

# Comments are used to explain code and are ignored by the Python interpreter
# Single-line comments start with #.
# Multi-line comments are enclosed in ''' or """.


# Escape Sequences

# Escape sequences are used to include special characters in strings.
# Common escape sequences:
# \n : Newline
# \t : Tab
# \\ : Backslash
# \" : Double quote
# \' : Single quote

print("Hello my name is Rohan\nI am good\twhat about you?\"who is\'your\\ best friend.")

# Print Statement

# The print() function is used to display output.
# You can use sep and end parameters to customize the output.

print("Hello world","What's up",5,'Yolo',sep="|", end='..')      # By default sep is space and end is new line.
print("Rohan", end='..')